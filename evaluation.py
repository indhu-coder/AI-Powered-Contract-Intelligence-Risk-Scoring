features = []

MAX_LENGTH = 384
DOC_STRIDE = 128

SPECIAL_TOKENS = tokenizer.num_special_tokens_to_add(pair=True)
PAD_ID = tokenizer.pad_token_id
CLS_ID = tokenizer.cls_token_id
SEP_ID = tokenizer.sep_token_id

if not tokenizer.is_fast:
    raise ValueError(
        "This snippet requires a fast tokenizer for offset mapping."
    )

if PAD_ID is None:
    raise ValueError("Tokenizer has no pad token.")

for example_index, ex in enumerate(examples):

    question = ex["question"].strip()
    context = ex["context"]

    # Tokenize the question separately.
    question_ids = tokenizer(
        question,
        add_special_tokens=False
    )["input_ids"]

    # Tokenize the full context directly through the fast
    # tokenizer backend to obtain token IDs and character offsets
    # without the regular model-length warning.
    context_encoding = tokenizer.backend_tokenizer.encode(
        context,
        add_special_tokens=False
    )

    context_ids = context_encoding.ids
    context_offsets = context_encoding.offsets

    # Calculate the maximum context length per chunk.
    max_context_tokens = (
        MAX_LENGTH - len(question_ids) - SPECIAL_TOKENS
    )

    if max_context_tokens <= DOC_STRIDE:
        raise ValueError(
            f"Question {example_index} is too long for chunking."
        )

    # The next chunk overlaps the previous chunk by DOC_STRIDE.
    step = max_context_tokens - DOC_STRIDE

    for chunk_start in range(0, len(context_ids), step):

        chunk_end = min(
            chunk_start + max_context_tokens,
            len(context_ids)
        )

        window_ids = context_ids[chunk_start:chunk_end]
        window_offsets = context_offsets[chunk_start:chunk_end]

        # BERT input: [CLS] question [SEP] context [SEP]
        input_ids = (
            [CLS_ID]
            + question_ids
            + [SEP_ID]
            + window_ids
            + [SEP_ID]
        )

        token_type_ids = (
            [0] * (len(question_ids) + 2)
            + [1] * (len(window_ids) + 1)
        )

        offsets = (
            [None] * (len(question_ids) + 2)
            + list(window_offsets)
            + [None]
        )

        attention_mask = [1] * len(input_ids)

        padding_length = MAX_LENGTH - len(input_ids)

        if padding_length < 0:
            raise ValueError(
                f"Input length {len(input_ids)} exceeds MAX_LENGTH."
            )

        input_ids += [PAD_ID] * padding_length
        attention_mask += [0] * padding_length
        token_type_ids += [0] * padding_length
        offsets += [None] * padding_length

        features.append({
            "example_index": example_index,
            "input_ids": input_ids,
            "attention_mask": attention_mask,
            "token_type_ids": token_type_ids,
            "offsets": offsets
        })

        if chunk_end == len(context_ids):
            break

